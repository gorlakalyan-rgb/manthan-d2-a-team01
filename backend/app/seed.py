"""Deterministic synthetic seed: 150 employees / 8 departments / hierarchy / 3,000 historical claims.

History is generated by running the real policy engine over generated lines, so flags are genuine.
Planted defects: duplicate receipts (same file hash), vendor+amount+date duplicates, limit breaches, weekend spend.
Usage:  python -m app.seed [--reset] [--claims 3000]
"""
from __future__ import annotations

import argparse
import hashlib
import random
from datetime import date, datetime, timedelta, timezone

from .auth import hash_password
from .db import Jsonb, apply_schema, connect, reset_schema
from .policy import DEFAULT_CONFIG, PolicyContext, evaluate_claim, is_sampled, norm_vendor, required_steps
from .workflow import bank_ref

DEPARTMENTS = ["Engineering", "Sales", "Marketing", "Finance", "Human Resources", "Operations", "Customer Success", "Legal"]
FIRST = ["Aarav", "Vivaan", "Aditya", "Vihaan", "Arjun", "Sai", "Reyansh", "Ayaan", "Krishna", "Ishaan", "Ananya", "Diya",
         "Saanvi", "Aadhya", "Pari", "Anika", "Navya", "Myra", "Sara", "Ira", "Kabir", "Rohan", "Meera", "Tara", "Neha",
         "Rahul", "Priya", "Kiran", "Dev", "Lakshmi"]
LAST = ["Sharma", "Verma", "Iyer", "Reddy", "Nair", "Gupta", "Patel", "Rao", "Menon", "Joshi", "Das", "Kulkarni",
        "Bose", "Pillai", "Shetty", "Khan", "Singh", "Mehta", "Chopra", "Banerjee"]
VENDORS = {
    "meals": ["Saravana Bhavan", "Barbeque Nation", "Haldiram's", "Cafe Coffee Day", "Swiggy", "Zomato", "MTR"],
    "hotel": ["Taj Hotels", "ITC Hotels", "Lemon Tree", "Ginger Hotels", "OYO Rooms", "Treebo"],
    "local_cab": ["Uber", "Ola", "Rapido", "Meru Cabs"],
    "airfare": ["IndiGo", "Air India", "Akasa Air", "SpiceJet"],
    "train": ["IRCTC"],
    "office_supplies": ["Staples India", "Amazon Business", "Reliance Digital"],
    "internet": ["Airtel", "Jio Fiber", "ACT Fibernet"],
    "other": ["Courier Express", "Print Hub", "Conference Desk"],
}
CITIES = ["Mumbai", "Delhi", "Bengaluru", "Chennai", "Hyderabad", "Pune", "Kolkata", "Indore", "Jaipur", "Kochi", "Raipur", "Nagpur"]
POLICY_ROWS = [
    ("MEAL_DAILY_LIMIT", "Meals per employee per day (paise), summed across claims", "ROUTE"),
    ("HOTEL_NIGHT_LIMIT_TIER1", "Hotel per night in tier-1 cities (paise)", "ROUTE"),
    ("HOTEL_NIGHT_LIMIT_OTHER", "Hotel per night in other cities (paise)", "ROUTE"),
    ("CAB_TRIP_LIMIT", "Local cab per trip (paise)", "ROUTE"),
    ("RECEIPT_REQUIRED_ABOVE", "Receipt mandatory for lines above this amount (paise)", "REJECT"),
    ("DUPLICATE_RECEIPT_HASH", "Reject a line whose receipt file hash was already used (1 = on)", "REJECT"),
    ("DUPLICATE_VENDOR_AMOUNT_DATE", "Flag same vendor + amount + date as an earlier line (1 = on)", "ROUTE"),
    ("WEEKEND_SPEND", "Flag weekend spend for manager attention (1 = on)", "ROUTE"),
    ("AUTO_APPROVE_MAX_TOTAL", "Clean claims above this total still need approval (paise)", "ROUTE"),
    ("AUDITOR_THRESHOLD", "Finance auditor approval above this claim total (paise)", "CONFIG"),
    ("HEAD_THRESHOLD", "Finance head approval above this claim total (paise)", "CONFIG"),
    ("SAMPLE_AUDIT_PERCENT", "Percent of auto-approved claims flagged for sample audit", "CONFIG"),
    ("TIER1_CITIES", "Cities that use the tier-1 hotel limit", "CONFIG"),
]
DEMO = "@demo.expenseflow.test"


def seed(conn, n_claims: int = 3000, rng_seed: int = 42, now: datetime | None = None) -> dict:
    rng = random.Random(rng_seed)
    now = now or datetime.now(timezone.utc)
    today = now.date()
    pw = hash_password("demo123", salt="demo-salt")

    for code, desc, outcome in POLICY_ROWS:
        conn.execute("INSERT INTO policy_rules (code, description, value, outcome) VALUES (%s,%s,%s,%s)",
                     (code, desc, Jsonb(DEFAULT_CONFIG[code]), outcome))
    dept_ids = {}
    for d in DEPARTMENTS:
        dept_ids[d] = conn.execute("INSERT INTO departments (name) VALUES (%s) RETURNING id", (d,)).fetchone()["id"]

    users: list[dict] = []
    used_names: set = set()

    def add_user(role, dept, manager_id, email=None, name=None):
        if not name:
            while True:
                name = f"{rng.choice(FIRST)} {rng.choice(LAST)}"
                if name not in used_names:
                    break
        used_names.add(name)
        uid = conn.execute("SELECT nextval('users_id_seq') AS id").fetchone()["id"]
        email = email or f"{name.lower().replace(' ', '.')}.{uid}@expenseflow.test"
        acct, ifsc = bank_ref(uid)
        conn.execute("""INSERT INTO users (id, name, email, role, department_id, manager_id, password_hash, account_ref, ifsc)
                        VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s)""",
                     (uid, name, email, role, dept_ids[dept], manager_id, pw, acct, ifsc))
        u = {"id": uid, "name": name, "role": role, "dept": dept, "manager_id": manager_id}
        users.append(u)
        return u

    # Hierarchy: head -> 8 department managers -> 2 team leads each -> employees. Auditors report to head.
    head = add_user("head", "Finance", None, f"head{DEMO}", "Farah Head")
    auditors = [add_user("auditor", "Finance", head["id"], f"auditor{DEMO}", "Arun Auditor")]
    auditors += [add_user("auditor", "Finance", head["id"]) for _ in range(2)]
    leads = []
    demo_manager = None
    for i, d in enumerate(DEPARTMENTS):
        dm = add_user("manager", d, head["id"])
        for j in range(2):
            if i == 0 and j == 0:
                demo_manager = add_user("manager", d, dm["id"], f"manager{DEMO}", "Maya Manager")
                leads.append(demo_manager)
            else:
                leads.append(add_user("manager", d, dm["id"]))
    demo_employee = add_user("employee", "Engineering", demo_manager["id"], f"employee{DEMO}", "Esha Employee")
    add_user("employee", "Engineering", demo_manager["id"], f"employee2{DEMO}", "Ravi Employee")
    while len(users) < 150:
        lead = leads[(len(users)) % len(leads)]
        add_user("employee", lead["dept"], lead["id"])
    conn.execute("SELECT setval('users_id_seq', (SELECT max(id) FROM users))")
    by_id = {u["id"]: u for u in users}

    # ---------------- historical claims
    claimants = [u for u in users if u["role"] != "head"]
    meal_totals: dict = {}          # (emp, date) -> paise
    hashes: set = set()
    vendor_keys: set = set()
    recent_lines: list = []         # for planting duplicates
    receipt_rows, line_rows, claim_rows, audit_rows = [], [], [], []
    receipt_id = 0
    stats = {"claims": 0, "dup_hash_planted": 0, "dup_vendor_planted": 0, "breach_planted": 0}

    def new_receipt(owner, sha=None):
        nonlocal receipt_id
        receipt_id += 1
        sha = sha or hashlib.sha256(f"r{receipt_id}-{rng.random()}".encode()).hexdigest()
        receipt_rows.append((receipt_id, owner, f"receipt-{receipt_id}.svg", "image/svg+xml", 1200, sha, "synthetic:"))
        return receipt_id, sha

    def make_line(emp, d):
        cat = rng.choices(["meals", "local_cab", "hotel", "airfare", "train", "office_supplies", "internet", "other"],
                          [30, 28, 14, 8, 6, 6, 4, 4])[0]
        city, nights = None, None
        if cat == "meals":
            amt = rng.randint(150, 1400) * 100
        elif cat == "local_cab":
            amt = rng.randint(120, 1900) * 100
        elif cat == "hotel":
            city, nights = rng.choice(CITIES), rng.randint(1, 3)
            per = 6000 if city in DEFAULT_CONFIG["TIER1_CITIES"] else 4000
            amt = rng.randint(int(per * 0.5), per) * 100 * nights
        elif cat == "airfare":
            amt = rng.randint(3500, 14000) * 100
        elif cat == "train":
            amt = rng.randint(400, 3000) * 100
        else:
            amt = rng.randint(200, 6000) * 100
        r = rng.random()
        if r < 0.06:                                    # planted limit breach
            stats["breach_planted"] += 1
            amt = {"meals": 210000, "local_cab": 265000}.get(cat, int(amt * 1.6))
        ln = {"category": cat, "amount_paise": amt, "expense_date": d, "vendor": rng.choice(VENDORS[cat]),
              "city": city, "nights": nights, "receipt_id": None, "receipt_sha256": None, "description": ""}
        if amt > 50000 or rng.random() < 0.5:
            if rng.random() > 0.02:                     # 2% of lines planted with a missing receipt
                ln["receipt_id"], ln["receipt_sha256"] = new_receipt(emp)
        return ln

    claim_id = 0
    for k in range(n_claims):
        emp = rng.choice(claimants)
        if k % 10 == 0:                                  # demo team files often, so demo queues are full
            emp = by_id[demo_employee["id"]] if k % 20 == 0 else by_id[demo_employee["id"] + 1]
        submitted = now - timedelta(days=rng.uniform(1, 180), hours=rng.uniform(0, 23))
        n_lines = rng.choices([1, 2, 3, 4], [35, 35, 20, 10])[0]
        lines = []
        for _ in range(n_lines):
            d = (submitted - timedelta(days=rng.randint(0, 20))).date()
            if d.weekday() >= 5 and rng.random() < 0.85:      # most spend is on weekdays
                d -= timedelta(days=d.weekday() - 4)
            lines.append(make_line(emp["id"], d))
        if rng.random() < 0.10:                              # planted big-ticket travel (> auditor / head thresholds)
            d = (submitted - timedelta(days=rng.randint(1, 10))).date()
            big = rng.choice([rng.randint(26000, 60000), rng.randint(60000, 95000), rng.randint(101000, 180000)]) * 100
            rid, sha = new_receipt(emp["id"])
            lines.append({"category": "airfare", "amount_paise": big, "expense_date": d, "vendor": rng.choice(VENDORS["airfare"]),
                          "city": None, "nights": None, "receipt_id": rid, "receipt_sha256": sha,
                          "description": "International conference travel"})
        if recent_lines and rng.random() < 0.025:       # planted duplicate receipt (same file hash)
            src = rng.choice(recent_lines)
            if src["receipt_sha256"]:
                stats["dup_hash_planted"] += 1
                rid, sha = new_receipt(emp["id"], src["receipt_sha256"])
                lines[0] = {**src, "receipt_id": rid, "receipt_sha256": sha}
        elif recent_lines and rng.random() < 0.03:      # planted vendor+amount+date duplicate
            src = rng.choice(recent_lines)
            stats["dup_vendor_planted"] += 1
            rid, sha = new_receipt(emp["id"])
            lines[0] = {**src, "receipt_id": rid, "receipt_sha256": sha}

        claim_id += 1
        ctx = PolicyContext(meal_totals_by_date={dd: v for (e, dd), v in meal_totals.items() if e == emp["id"]},
                            existing_receipt_hashes=hashes, existing_vendor_keys=vendor_keys)
        res = evaluate_claim(lines, DEFAULT_CONFIG, ctx)
        total = res["total_paise"]
        flags = sorted({r["code"] for lr in res["lines"] for r in lr["reasons"]} | {r["code"] for r in res["claim_reasons"]})
        steps, step, decided, paid, sample, auto = [], None, None, None, False, False
        age_days = (now - submitted).days
        events = [("submit_" + {"REJECT": "auto_rejected", "APPROVE": "auto_approved", "ROUTE": "routed"}[res["outcome"]],
                   None, emp["id"], submitted)]
        if res["outcome"] == "REJECT":
            status, decided = "AUTO_REJECTED", submitted
        elif res["outcome"] == "APPROVE":
            auto, decided = True, submitted
            sample = is_sampled(claim_id, 10)
            status = "SAMPLE_AUDIT" if sample and age_days < 40 else "APPROVED"
            if sample and status == "APPROVED":
                events.append(("sample_audit_cleared", "APPROVED", auditors[0]["id"], submitted + timedelta(days=1)))
        else:
            steps = required_steps(total, DEFAULT_CONFIG)
            if not emp["manager_id"]:
                steps = [s for s in steps if s != "MANAGER"] or ["AUDITOR"]
            t = submitted
            status = "APPROVED"
            for s in steps:
                t = t + timedelta(hours=rng.uniform(2, 60))
                approver = {"MANAGER": emp["manager_id"], "AUDITOR": rng.choice(auditors)["id"], "HEAD": head["id"]}[s]
                if t > now - timedelta(hours=1) or (age_days < 12 and rng.random() < 0.55):
                    status, step = "PENDING_APPROVAL", s
                    break
                roll = rng.random()
                if roll < 0.06:
                    status, decided = "REJECTED", t
                    events.append((f"reject_{s.lower()}", "REJECTED", approver, t))
                    break
                if roll < 0.08 and age_days < 20:
                    status = "NEEDS_CLARIFICATION"
                    events.append((f"send_back_{s.lower()}", "NEEDS_CLARIFICATION", approver, t))
                    break
                events.append((f"approve_{s.lower()}", None, approver, t))
                decided = t
        step_entered = None
        if status == "PENDING_APPROVAL":
            # Healthy baseline: nothing waits > 48h at its current step (the SRE drill creates the stale one).
            step_entered = now - timedelta(hours=rng.uniform(1, 46))
        if status == "APPROVED" and age_days > 12:
            status, paid = "PAID", (decided or submitted) + timedelta(days=rng.randint(3, 9))
        claim_rows.append((claim_id, emp["id"], f"{rng.choice(['Client visit', 'Team offsite', 'Conference', 'Sales trip', 'Office purchase', 'Training'])} - {submitted:%b %Y}",
                           status, step, steps, total, res["outcome"], auto, sample, flags, submitted, now if status == "PENDING_APPROVAL" else (paid or decided or submitted),
                           submitted, step_entered, decided if status not in ("PENDING_APPROVAL", "NEEDS_CLARIFICATION", "SAMPLE_AUDIT") else None, paid))
        for i, (ln, lr) in enumerate(zip(lines, res["lines"]), 1):
            line_rows.append((claim_id, i, ln["category"], ln["amount_paise"], ln["expense_date"], ln["vendor"], ln["city"],
                              ln["nights"], ln.get("description") or "", ln["receipt_id"], lr["outcome"], Jsonb(lr["reasons"])))
        prev = "DRAFT"
        for action, to, actor, at in events:
            to_s = to or (status if action == events[-1][0] else "PENDING_APPROVAL")
            audit_rows.append((at, actor, "claim", claim_id, action, prev, to_s, None, Jsonb({"seeded": True})))
            prev = to_s
        if status == "PAID":
            audit_rows.append((paid, head["id"], "claim", claim_id, "paid", "IN_PAYOUT", "PAID", None, Jsonb({"seeded": True})))
        if status not in ("AUTO_REJECTED", "REJECTED"):
            for ln in lines:
                if ln["category"] == "meals":
                    key = (emp["id"], ln["expense_date"])
                    meal_totals[key] = meal_totals.get(key, 0) + ln["amount_paise"]
                if ln["receipt_sha256"]:
                    hashes.add(ln["receipt_sha256"])
                vendor_keys.add((norm_vendor(ln["vendor"]), ln["amount_paise"], ln["expense_date"]))
            recent_lines.extend(lines)
            recent_lines[:] = recent_lines[-400:]
        stats["claims"] += 1

    with conn.cursor() as cur:
        cur.executemany("""INSERT INTO receipts (id, owner_id, filename, content_type, size_bytes, sha256, storage_path)
                           VALUES (%s,%s,%s,%s,%s,%s,%s)""", receipt_rows)
        cur.executemany("""INSERT INTO claims (id, employee_id, title, status, current_step, required_steps, total_paise,
                           policy_outcome, auto_approved, sample_audit, flags, created_at, updated_at, submitted_at,
                           step_entered_at, decided_at, paid_at) VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)""",
                        claim_rows)
        cur.executemany("""INSERT INTO claim_lines (claim_id, line_no, category, amount_paise, expense_date, vendor, city,
                           nights, description, receipt_id, outcome, reasons) VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)""",
                        line_rows)
        cur.executemany("""INSERT INTO audit_log (at, actor_id, entity, entity_id, action, from_status, to_status, comment, details)
                           VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s)""", audit_rows)
    conn.execute("SELECT setval('claims_id_seq', (SELECT max(id) FROM claims))")
    conn.execute("SELECT setval('receipts_id_seq', (SELECT max(id) FROM receipts))")

    # Payout history: weekly batches of PAID claims.
    paid_claims = conn.execute("SELECT id, total_paise, paid_at FROM claims WHERE status='PAID' ORDER BY paid_at").fetchall()
    batches: dict = {}
    for c in paid_claims:
        wk = c["paid_at"].date() - timedelta(days=c["paid_at"].weekday())
        batches.setdefault(wk, []).append(c)
    for wk, items in sorted(batches.items()):
        paid_at = datetime.combine(wk + timedelta(days=4), datetime.min.time(), tzinfo=timezone.utc)
        bid = conn.execute("""INSERT INTO payout_batches (created_by, created_at, status, paid_at, total_paise, claim_count)
                              VALUES (%s,%s,'PAID',%s,%s,%s) RETURNING id""",
                           (head["id"], paid_at, paid_at, sum(i["total_paise"] for i in items), len(items))).fetchone()["id"]
        with conn.cursor() as cur:
            cur.executemany("INSERT INTO payout_items (batch_id, claim_id, line_no, amount_paise) VALUES (%s,%s,%s,%s)",
                            [(bid, i["id"], n, i["total_paise"]) for n, i in enumerate(items, 1)])
    stats["users"] = len(users)
    stats["departments"] = len(DEPARTMENTS)
    stats["receipts"] = len(receipt_rows)
    stats["lines"] = len(line_rows)
    return stats


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--reset", action="store_true", help="drop and recreate the schema first")
    ap.add_argument("--if-empty", action="store_true", help="only seed when the users table is empty")
    ap.add_argument("--claims", type=int, default=3000)
    a = ap.parse_args()
    with connect() as conn:
        if a.reset:
            reset_schema(conn)
        else:
            apply_schema(conn)
        if a.if_empty and conn.execute("SELECT count(*) AS n FROM users").fetchone()["n"] > 0:
            print("seed: data already present, skipping")
            return
        stats = seed(conn, a.claims)
        conn.commit()
        print("seed:", stats)


if __name__ == "__main__":
    main()
